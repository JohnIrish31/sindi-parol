export const TEXT: Record<Lang, Dict> = { en, tl };
export const t = (lang: Lang): Dict => TEXT[lang];

export function joinNames(lang: Lang, names: string[]): string {
  if (names.length < 2) return names.join('');
  return `${names.slice(0, -1).join(', ')} ${TEXT[lang].and} ${names[names.length - 1]}`;
}
